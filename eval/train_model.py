#!/usr/bin/env python3
"""Train the shipped scoring model on replay datasets, and report how it
does on repos it wasn't trained on.

  python eval/train_model.py replay_requests.jsonl.gz replay_flask.jsonl.gz ... [--write]

Leave-one-repo-out: for each dataset, a model is fit on all the others and
scored on it, next to the old hand-weighted scoring and history alone. These
are the numbers to report; the model written with --write (trained on every
dataset) is the one that ships.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
sys.path.insert(0, str(Path(__file__).parent))

import score_replay as sr
from codebase_intel.core.scoring import FEATURES, featurize

WEIGHTS_FILE = Path(__file__).parent.parent / "codebase_intel" / "core" / "model_weights.py"


def rows(queries: list[dict]) -> list[tuple[list[float], int]]:
    return [(featurize(c), int(c["file"] == q["hidden"])) for q in queries if q["hidden"] for c in q["candidates"]]


def fit_raw(train: list[tuple[list[float], int]]) -> tuple[float, dict[str, float]]:
    """Logistic regression coefficients in raw feature units."""
    import numpy as np
    X = np.array([x for x, _ in train])
    y = np.array([t for _, t in train], dtype=float)
    mu, sd = X.mean(0), X.std(0) + 1e-9
    Z = np.c_[np.ones(len(X)), (X - mu) / sd]
    w = np.zeros(Z.shape[1])
    reg = np.eye(len(w))
    reg[0, 0] = 0
    for _ in range(100):
        p = 1 / (1 + np.exp(-Z @ w))
        step = np.linalg.solve((Z * (p * (1 - p))[:, None]).T @ Z + reg, Z.T @ (p - y) + reg @ w)
        w -= step
        if np.abs(step).max() < 1e-8:
            break
    coef = w[1:] / sd
    return float(w[0] - coef @ mu), dict(zip(FEATURES, map(float, coef)))


def model_from(bias: float, weights: dict[str, float]):
    import math
    return lambda c: 1 / (1 + math.exp(-(bias + sum(weights[f] * v for f, v in zip(FEATURES, featurize(c))))))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("datasets", nargs="+")
    parser.add_argument("--write", action="store_true", help=f"Write the all-data model to {WEIGHTS_FILE.name}")
    parser.add_argument("--out", help="Save the leave-one-repo-out results as JSON")
    args = parser.parse_args()

    data = {Path(p).name.split("_")[0]: sr.load(p) for p in args.datasets}
    history = lambda c: min(0.9, 0.4 + 0.5 * c["cc_p"]) if c["cc_n"] >= 2 else 0.0
    results = {}
    for test, queries in data.items():
        model = model_from(*fit_raw([r for name, qs in data.items() if name != test for r in rows(qs)]))
        results[test] = {}
        for label, score, key in (("before", sr.baseline, sr.baseline_key),
                                  ("history_only", history, lambda c: (history(c), c["cc_p"])),
                                  ("model", model, None)):
            m = sr.evaluate(queries, score, key)
            results[test][label] = m
            print(f"{test:<9} {label:<12} hit@1={m['hit@1']:.3f} hit@5={m['hit@5']:.3f} mrr={m['mrr']:.3f}  "
                  f"@p0.2 R {m['recall@p0.2']:.2f} P {m['precision@p0.2']:.2f} FA {m['false_alarms@p0.2']:.2f}  n={m['n']}")
    if args.out:
        Path(args.out).write_text(json.dumps(results, indent=2))

    if args.write:
        bias, weights = fit_raw([r for qs in data.values() for r in rows(qs)])
        lines = [
            '"""Generated by eval/train_model.py from replays of: ' + ", ".join(data) + '. Do not edit."""',
            f"BIAS = {bias:.6f}",
            "WEIGHTS = {",
            *[f'    "{k}": {v:.6f},' for k, v in weights.items()],
            "}",
            "",
        ]
        WEIGHTS_FILE.write_text("\n".join(lines))
        print(f"Wrote {WEIGHTS_FILE}")


if __name__ == "__main__":
    main()
